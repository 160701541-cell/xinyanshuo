export function itemIconId(name) {
  const s = String(name || '');
  for (const [key, id] of ITEM_ALIAS) if (s.includes(key)) return id;
  return 'grain';   // 认不出来就当杂粮，别落到石头
}

export function itemIcon(id) {
  const rows = ICONS[id] || ICONS.stone;
  return {id, w: W, h: H, rows, palette: PAL[id] || PAL.stone};
}

export function itemArtSVG(id, size = 96) {
  const ic = itemIcon(id);
  const out = [`<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${W} ${H}" shape-rendering="crispEdges">`];
  for (let y = 0; y < ic.rows.length; y++) {
    const row = ic.rows[y] || '';
    for (let x = 0; x < row.length; x++) {
      const c = row[x];
      if (c === '.' || c === ' ') continue;
      const col = ic.palette[Number(c) - 1];
      if (col) out.push(`<rect x="${x}" y="${y}" width="1" height="1" fill="${col}"/>`);
    }
  }
  out.push('</svg>');
  return out.join('');
}

