const ALIAS = new Map();
for (const [id, icon] of Object.entries(ICONS)) {
  for (const a of icon.aliases) if (!ALIAS.has(a)) ALIAS.set(a, id);
}

/** 按名字猜图标：先整名命中，再逐字/逐词包含；都不认识就落 generic。 */
export function iconIdFor(name = '') {
  const n = String(name);
  if (ALIAS.has(n)) return ALIAS.get(n);
  let best = null;
  for (const [alias, id] of ALIAS) {
    if (n.includes(alias) && (!best || alias.length > best.alias.length)) best = {alias, id};
  }
  return best ? best.id : 'generic';
}

export function iconFor(name, paletteOverride) {
  const id = iconIdFor(name);
  const icon = ICONS[id] || ICONS.generic;
  return {id, palette: PALETTES[paletteOverride || icon.palette], rows: icon.rows};
}

/** 渲染到 canvas：整数倍放大，保持像素边缘。 */
export function drawIcon(ctx, icon, x, y, size) {
  const n = icon.rows.length, px = size / n;
  for (let j = 0; j < n; j++) {
    const row = icon.rows[j];
    for (let i = 0; i < row.length; i++) {
      const ch = row[i];
      if (ch === '.') continue;
      const color = icon.palette[ch];
      if (!color) continue;
      ctx.fillStyle = color;
      ctx.fillRect(x + i * px, y + j * px, Math.ceil(px), Math.ceil(px));
    }
  }
}

/** 输出 SVG：给文档预览与离线渲染用，和游戏里同一份配方。 */
export function iconSVG(icon, size = 64) {
  const n = icon.rows.length, px = size / n;
  let out = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}" shape-rendering="crispEdges">`;
  for (let j = 0; j < n; j++) {
    for (let i = 0; i < icon.rows[j].length; i++) {
      const ch = icon.rows[j][i];
      if (ch === '.' || !icon.palette[ch]) continue;
      out += `<rect x="${(i * px).toFixed(2)}" y="${(j * px).toFixed(2)}" width="${px.toFixed(2)}" height="${px.toFixed(2)}" fill="${icon.palette[ch]}"/>`;
    }
  }
  return out + '</svg>';
}

