#!/usr/bin/env python3
"""Convert catalog SPEC_ONLY entries into reviewable ComfyUI jobs.
No images are generated by this step. Keeps existing jobs.json untouched.
"""
import argparse
import json
from pathlib import Path
from starter_village_catalog import build, validate

STYLE = ("premium hand-painted Chinese xianxia HD2D game asset; consistent 3/4 overhead "
         "isometric view, soft daylight, precise outlines, readable at gameplay scale, "
         "authentic materials, isolated single subject on transparent background, "
         "no background scenery, no ground plate, no label, no text, no border, no watermark")
TRANSLATIONS = {
 "terrain": "seamless game terrain tile; consistent tile footprint and boundary connections",
 "buildings": "standalone Chinese vernacular building, complete silhouette and grounded base",
 "architecture": "modular architecture part with consistent attachment points and orientation",
 "vegetation": "isolated plant or natural object, rooted at stable ground contact anchor",
 "props": "isolated interactive world prop, complete silhouette",
 "actors": "single full-body character sprite with consistent size and feet anchor",
 "equipment": "single inventory or world equipment prop"
}


def make_jobs(catalog, batch=0, family=None):
    validate(catalog)
    selected = [x for x in catalog["assets"] if family is None or x["family"] == family]
    if batch:
        selected = selected[:batch]
    jobs = []
    for x in selected:
        variant = x["variant"]
        state = "-".join(variant.values())
        prompt = (STYLE + ". " + TRANSLATIONS[x["family"]] + ". "
                  + "Subject: " + x["kind"].replace("_", " ") + ". "
                  + "Variant: " + json.dumps(variant, ensure_ascii=False) + ". "
                  + "Keep canonical form, scale, orthographic camera, stable silhouette "
                  + "and attachment anchors consistent across states and directions.")
        jobs.append({
            "id": x["prototype_id"], "name": x["kind"], "state": state,
            "prompt_node": "6", "prompt": prompt,
            "demand_id": x["id"], "family": x["family"],
            "status": "PENDING_GENERATION", "quality_gate": "UNAPPROVED",
            "world_png_target": x["world_png"], "icon_png_target": x["icon_png"]
        })
    ids = [(j["id"], j["state"]) for j in jobs]
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate production jobs")
    return jobs


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--out", default="tools/asset_factory/starter_village_jobs.json")
    p.add_argument("--batch", type=int, default=0)
    p.add_argument("--family", choices=list(TRANSLATIONS))
    a = p.parse_args()
    if a.batch < 0:
        p.error("--batch must be >= 0")
    catalog = build()
    jobs = make_jobs(catalog, batch=a.batch, family=a.family)
    dest = Path(a.out)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(jobs, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Prepared {len(jobs)} unapproved jobs; 0 PNG generated; output: {dest}")


if __name__ == "__main__":
    main()
