#!/usr/bin/env python3
"""Stage (NEVER publish) next revision for the *installed* original APK176.

Inputs are generated by an exact-original-main APK176 Godot QA run.  Neither a
standalone game-source/godot3d PCK nor a historic rev178 artifact qualifies.
The caller separately checks GitHub's QA job conclusion == success before use.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import pathlib
import shutil
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "logic-qa" / "release-gate"))
from ota_release_gate import HOST, check_candidate, pubkey, verify_signature
from publish_original_rev177_ota import matching_original_private
from sign_pck_release import build_manifest, sign_manifest

PASS_MARKER = "PASS_APK176_ACTUAL_MAIN_INSTANTIATED_NO_ENGINE_ERRORS_WITH_REAL_HOUSE"
OBSERVED_MARKER = "OBSERVED_APK176_MAIN_INSTANCE_WITH_PORTAL_AND_IMAGES_PENDING_ENGINE_ERROR_AUDIT"
DANGEROUS_LOG_MARKERS = (
    "SCRIPT ERROR:", "Parse Error:", "ERROR:", "FAIL_APK176_ACTUAL_MAIN_RUNTIME",
    "Failed loading resource",
)


def validate_original_qa(pack: pathlib.Path, template: pathlib.Path,
                         runtime: pathlib.Path, base: dict, current: dict) -> tuple[int, dict]:
    if base.get("package_name") != "org.canglan.ancient25d.preview" or base.get("version_code") != 1176:
        raise ValueError("BLOCKED: this is not the original installed APK176")
    if not verify_signature(current, pubkey()):
        raise ValueError("BLOCKED: current public feed signature is invalid")
    revision = current["revision"] + 1
    unsigned = json.loads(template.read_text(encoding="utf-8"))
    expected = HOST + "canglan-content-rev-%d.pck" % revision
    if not (unsigned.get("_not_a_release") == "UNSIGNED_DEVELOPER_TEMPLATE_DO_NOT_HOST"
            and unsigned.get("signature") == ""
            and unsigned.get("schema") == 1
            and unsigned.get("revision") == revision
            and unsigned.get("minimum_android_code") == 1176
            and unsigned.get("maximum_android_code") == 1176
            and unsigned.get("pack_url") == expected):
        raise ValueError("BLOCKED: QA candidate is not next-revision APK176 template")
    if not pack.is_file() or not 512 <= pack.stat().st_size <= 95 * 1024 * 1024:
        raise ValueError("BLOCKED: candidate pack missing or over public Pages release limit")
    digest = hashlib.sha256(pack.read_bytes()).hexdigest()
    if pack.read_bytes()[:4] != b"GDPC" or digest != unsigned.get("sha256") or pack.stat().st_size != unsigned.get("size_bytes"):
        raise ValueError("BLOCKED: unsigned QA candidate differs from PCK bytes")
    log = runtime.read_text(encoding="utf-8")
    if OBSERVED_MARKER not in log or any(x in log for x in DANGEROUS_LOG_MARKERS):
        raise ValueError("BLOCKED: original exported main scene Godot runtime QA failed")
    # Exactly this historical assertion is performed by the original APK176
    # main-scene CI job; a log alone is not a substitute for its SUCCESS status.
    return revision, unsigned


def stage(args: argparse.Namespace) -> dict:
    root = args.repository.resolve()
    base = json.loads((root / "android-preview/base-latest.json").read_text(encoding="utf-8"))
    current = json.loads((root / "android-preview/latest.json").read_text(encoding="utf-8"))
    revision, unsigned = validate_original_qa(args.pck, args.qa_template,
                                               args.qa_runtime_log, base, current)
    if not args.original_qa_success:
        raise ValueError("BLOCKED: source workflow's original-main runtime SUCCESS not attested")
    private = matching_original_private()
    if private is None:
        raise ValueError("BLOCKED: matching original APK176 RSA signer not injected")
    pack_name = "canglan-content-rev-%d.pck" % revision
    with tempfile.TemporaryDirectory(prefix="canglan-original-next-stage-") as tmp:
        d = pathlib.Path(tmp)
        pk = d / "signing.pem"
        pk.write_bytes(private)
        pk.chmod(0o600)
        original_pub = d / "original.pem"
        original_pub.write_text(pubkey(), encoding="utf-8")
        copied = d / pack_name
        shutil.copyfile(args.pck, copied)
        manifest = build_manifest(copied, revision, 1176, 1176, HOST + pack_name,
                                  unsigned["notes"])
        signed = sign_manifest(manifest, pk, original_pub)
        if not verify_signature(signed, pubkey()):
            raise ValueError("BLOCKED: manifest rejected by pinned original public key")
        result = check_candidate(signed, copied, base, current)
        if not result["passed"]:
            raise ValueError("BLOCKED: release gate: " + "; ".join(result["errors"]))
        # Stage in a separate output folder, never mutate latest.json here.
        dest = args.output.resolve()
        dest.mkdir(parents=True, exist_ok=True)
        for filename in [pack_name, "latest.json"]:
            if (dest / filename).exists():
                raise ValueError("BLOCKED: staging would overwrite an existing artifact")
        shutil.copyfile(copied, dest / pack_name)
        (dest / "latest.json").write_text(
            json.dumps(signed, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        report = {
            "status": "STAGED_ONLY_UNPUBLISHED_REQUIRES_ATOMIC_PUBLIC_RELEASE",
            "revision": revision, "original_android_code": 1176,
            "pack_sha256": signed["sha256"], "pack_size_bytes": signed["size_bytes"],
            "original_qa_workflow_pass_required": True,
            "original_rsa_signature_verified": True,
            "source": "original_APK176_exported_main_scene_not_standalone_3D",
        }
        (dest / "staging-report.json").write_text(
            json.dumps(report, indent=2) + "\n", encoding="utf-8")
        return report


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--repository", type=pathlib.Path, default=ROOT)
    p.add_argument("--pck", type=pathlib.Path, required=True)
    p.add_argument("--qa-template", type=pathlib.Path, required=True)
    p.add_argument("--qa-runtime-log", type=pathlib.Path, required=True)
    p.add_argument("--original-qa-success", action="store_true",
                   help="Caller must have verified original Godot Actions job success")
    p.add_argument("--output", type=pathlib.Path, required=True)
    a = p.parse_args()
    try:
        result = stage(a)
    except (ValueError, OSError, KeyError, json.JSONDecodeError) as exc:
        p.exit(2, str(exc) + "\n")
    print(json.dumps(result, ensure_ascii=False))


if __name__ == "__main__":
    main()
